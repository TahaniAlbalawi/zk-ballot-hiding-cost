#!/usr/bin/env python3
"""Generate the manuscript's results tables and figure data from the analysis outputs.

Reads <experiment-dir>/runs.jsonl, artifacts.json, analysis/summary.json and
analysis/paper_analysis.json, and writes:

  <output-dir>/tables/tab_time_rows.tex        proof time per cell, contrasts, Holm p (Table 6)
  <output-dir>/tables/tab_memory_rows.tex      proving memory per cell, contrast, Holm p (Table 7)
  <output-dir>/tables/tab_gas_rows.tex         cast gas per workflow (Table 8)
  <output-dir>/tables/tab_result_rows.tex      result-phase gas and total gas per ballot (Table 9)
  <output-dir>/figures/data/time_measured.dat  block-level proof time per circuit and depth (Figure 2)
  <output-dir>/figures/data/time_model.dat     time model for every depth 5..20 (Figure 2)
  <output-dir>/figures/data/gas_per_ballot.dat cast and result gas per ballot (Figure 3)
  <experiment-dir>/analysis/paper_numbers.json the numbers quoted in the text

Every number in these files comes from the experiment outputs; nothing is typed by hand.
Usage (from the repository root): python3 -I analysis/make_paper_tables.py <experiment-dir> <output-dir>
<output-dir> is the manuscript directory, or paper/ in the public repository.
"""
import json
import math
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

PUB, PBR, REV = "PUBLIC_DISCLOSURE", "COMMITMENT_BALLOT_HIDING", "COMMITMENT_ONCHAIN_REVEAL"
T975 = {5: 2.5705818, 11: 2.2009852}  # two-sided 95% Student-t quantiles for the block counts used

GROUPS = [
    ("Merkle depth ($C = 4$, $B = 32$)", ["DEPTH-D05", "DEPTH-D08", "DEPTH-D10", "DEPTH-D12", "DEPTH-D13", "DEPTH-D16", "DEPTH-D20"]),
    ("Candidates ($D = 10$, $B = 32$)", ["CAND-C02", "CAND-C08"]),
    ("Election size ($D = 16$, $C = 4$)", ["SCALE-B0128", "SCALE-B0512", "SCALE-B1024"]),
]


def label(cell: str) -> str:
    family, value = cell.split("-")
    number = int(value[1:])
    symbol = {"DEPTH": "D", "CAND": "C", "SCALE": "B"}[family]
    return f"${symbol} = {number}$"


def num(x: float, digits: int = 1) -> str:
    s = f"{abs(x):,.{digits}f}"
    return ("$-$" if x < 0 and float(f"{abs(x):.{digits}f}") != 0 else "") + s


def ci(lo: float, hi: float, digits: int = 1) -> str:
    return f"[{num(lo, digits)}, {num(hi, digits)}]"


def pval(p: float) -> str:
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}" if p < 0.01 else f"{p:.2f}"


def main() -> None:
    exp, ms = Path(sys.argv[1]), Path(sys.argv[2])
    runs = [json.loads(l) for l in (exp / "runs.jsonl").read_text().splitlines() if l.strip()]
    artifacts = {a["configuration"]: a for a in json.loads((exp / "artifacts.json").read_text())}
    summary = json.loads((exp / "analysis" / "summary.json").read_text())
    paper = json.loads((exp / "analysis" / "paper_analysis.json").read_text())
    (ms / "tables").mkdir(parents=True, exist_ok=True)
    (ms / "figures" / "data").mkdir(parents=True, exist_ok=True)

    absolute = {(r["cellId"], r["workflow"], r["outcome"]): r for r in summary["absolute"]}
    contrast = {(r["contrast"], r["outcome"], r["cellId"]): r for r in summary["contrasts"]}
    config_of = {r["cellId"]: r["configuration"] for r in runs}

    def constraint_ratio(cell: str) -> float:
        a = artifacts[config_of[cell]]
        return a["commitment"]["constraints"] / a["public"]["constraints"]

    # ---------------------------------------------------------------- Table: proof time
    rows = []
    for title, cells in GROUPS:
        rows.append(f"\\multicolumn{{9}}{{l}}{{\\textit{{{title}}}}}\\\\")
        for cell in cells:
            a = {w: absolute[(cell, w, "proofMs")] for w in (PUB, PBR, REV)}
            c1 = contrast[("publisher-public", "proofMs", cell)]
            c3 = contrast[("reveal-publisher", "proofMs", cell)]
            bold = cell == "DEPTH-D13"
            cells_tex = [
                label(cell),
                f"{constraint_ratio(cell):.3f}",
                *(f"{num(a[w]['mean'])} ({num(a[w]['sd'])})" for w in (PUB, PBR, REV)),
                f"{num(c1['mean'])} {ci(c1['ciLow'], c1['ciHigh'])}",
                f"{c1['meanRatio']:.3f}",
                pval(c1["holmP"]),
                f"{num(c3['mean'])} {ci(c3['ciLow'], c3['ciHigh'])}",
            ]
            if bold:
                cells_tex = [f"\\textbf{{{x}}}" for x in cells_tex]
            rows.append(" & ".join(cells_tex) + "\\\\")
    (ms / "tables" / "tab_time_rows.tex").write_text("% generated by analysis/make_paper_tables.py\n" + "\n".join(rows) + "\n")

    # ---------------------------------------------------------------- Table: memory
    rows = []
    for title, cells in GROUPS:
        rows.append(f"\\multicolumn{{7}}{{l}}{{\\textit{{{title}}}}}\\\\")
        for cell in cells:
            a = {w: absolute[(cell, w, "provingMemoryMiB")] for w in (PUB, PBR, REV)}
            c1 = contrast[("publisher-public", "provingMemoryMiB", cell)]
            art = artifacts[config_of[cell]]
            key = f"{art['public']['zkeyBytes'] / 2**20:.2f}/{art['commitment']['zkeyBytes'] / 2**20:.2f}"
            cells_tex = [label(cell), key,
                         *(f"{num(a[w]['mean'], 0)} ({num(a[w]['sd'], 1)})" for w in (PUB, PBR, REV)),
                         f"{num(c1['mean'])} {ci(c1['ciLow'], c1['ciHigh'])}", pval(c1["holmP"])]
            if cell == "DEPTH-D13":
                cells_tex = [f"\\textbf{{{x}}}" for x in cells_tex]
            rows.append(" & ".join(cells_tex) + "\\\\")
    (ms / "tables" / "tab_memory_rows.tex").write_text("% generated by analysis/make_paper_tables.py\n" + "\n".join(rows) + "\n")

    # ---------------------------------------------------------------- Table: result phase and totals
    def runs_of(selector, workflow):
        return [r for r in runs if selector(r) and r["workflow"] == workflow]

    elections = [
        ("$B = 32$, $C = 2$", lambda r: r["cellId"] == "CAND-C02"),
        ("$B = 32$, $C = 4$", lambda r: r["family"] == "DEPTH"),
        ("$B = 32$, $C = 8$", lambda r: r["cellId"] == "CAND-C08"),
        ("$B = 128$, $C = 4$", lambda r: r["cellId"] == "SCALE-B0128"),
        ("$B = 512$, $C = 4$", lambda r: r["cellId"] == "SCALE-B0512"),
        ("$B = 1024$, $C = 4$", lambda r: r["cellId"] == "SCALE-B1024"),
    ]
    rows, bars = [], {}
    for name, sel in elections:
        per = {}
        for w in (PUB, PBR, REV):
            rs = runs_of(sel, w)
            cast = st.mean(st.mean(b["castGas"] for b in r["ballots"]) for r in rs)
            result = st.mean(r["result"]["resultGas"] for r in rs)
            b = rs[0]["plannedBallots"]
            per[w] = {"cast": cast, "result": result, "result_pb": result / b, "total_pb": cast + result / b,
                      "time_s": st.mean(r["result"]["resultMs"] for r in rs) / 1000}
        base = per[PUB]["total_pb"]
        rel = lambda w: f"{per[w]['total_pb']:,.0f} (+{(per[w]['total_pb'] / base - 1) * 100:.1f}\\%)"
        rows.append(" & ".join([
            name,
            f"{per[PBR]['result']:,.0f}", f"{per[REV]['result']:,.0f}",
            f"{per[REV]['result'] / per[PBR]['result']:.1f}",
            f"{base:,.0f}", rel(PBR), rel(REV),
        ]) + "\\\\")
        bars[name] = per
    (ms / "tables" / "tab_result_rows.tex").write_text("% generated by analysis/make_paper_tables.py\n" + "\n".join(rows) + "\n")

    # ---------------------------------------------------------------- Figure data: proof time per circuit
    lines = ["D Npub Ncom pub pub_lo pub_hi com com_lo com_hi ratio constraint_ratio"]
    for cell in GROUPS[0][1]:
        blocks = defaultdict(dict)
        for r in runs:
            if r["cellId"] == cell:
                blocks[r["block"]][r["workflow"]] = st.mean(b["witnessMs"] + b["proveMs"] for b in r["ballots"])
        pub = [v[PUB] for v in blocks.values()]
        com = [(v[PBR] + v[REV]) / 2 for v in blocks.values()]
        ratio = st.mean(((v[PBR] + v[REV]) / 2) / v[PUB] for v in blocks.values())
        q = T975[len(pub) - 1]
        hp = q * st.stdev(pub) / math.sqrt(len(pub))
        hc = q * st.stdev(com) / math.sqrt(len(com))
        art = artifacts[config_of[cell]]
        d = runs[[r["cellId"] for r in runs].index(cell)]["depth"]
        lines.append(f"{d} {art['public']['domainSize']} {art['commitment']['domainSize']} "
                     f"{st.mean(pub):.2f} {st.mean(pub) - hp:.2f} {st.mean(pub) + hp:.2f} "
                     f"{st.mean(com):.2f} {st.mean(com) - hc:.2f} {st.mean(com) + hc:.2f} "
                     f"{ratio:.4f} {constraint_ratio(cell):.4f}")
    (ms / "figures" / "data" / "time_measured.dat").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Figure data: time model at every depth
    tm = paper["time_model"]
    alpha, kappa = tm["alpha_ms_per_wire"], {int(k): v for k, v in tm["kappa_ms"].items()}
    ell = 6

    def domain(rows_needed: int) -> int:
        return 2 ** math.ceil(math.log2(rows_needed))

    lines = ["D pub com ratio constraint_ratio"]
    for d in range(5, 21):
        n_pub, n_com = 950 + 524 * d, 950 + 524 * d + 517
        m_pub, m_com = 953 + 525 * d, 953 + 525 * d + 518  # wires, exact for all measured depths
        t_pub = alpha * m_pub + kappa[domain(n_pub + ell + 1)]
        t_com = alpha * m_com + kappa[domain(n_com + ell + 1)]
        lines.append(f"{d} {t_pub:.2f} {t_com:.2f} {t_com / t_pub:.4f} {n_com / n_pub:.4f}")
    # guard: the wire formula must reproduce every measured key
    for cfg, a in artifacts.items():
        d = int(cfg[1:3])
        assert a["public"]["wires"] == 953 + 525 * d and a["commitment"]["wires"] == 953 + 525 * d + 518, cfg
    (ms / "figures" / "data" / "time_model.dat").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Figure data: gas per ballot (kgas)
    lines = ["x B workflow cast result total label"]
    x = 0
    for name in ("$B = 32$, $C = 4$", "$B = 1024$, $C = 4$"):
        for w, wname in ((PUB, "Public"), (PBR, "Publisher"), (REV, "Reveal")):
            x += 1
            p = bars[name][w]
            lines.append(f"{x} {name.split(',')[0].strip('$').split('= ')[1]} {wname} "
                         f"{p['cast'] / 1000:.3f} {p['result_pb'] / 1000:.3f} {p['total_pb'] / 1000:.3f} {p['total_pb'] / 1000:.0f}")
        x += 1  # gap between the two groups
    (ms / "figures" / "data" / "gas_per_ballot.dat").write_text("\n".join(lines) + "\n")

    # ---------------------------------------------------------------- Table: cast gas decomposition (pooled over all cells)
    steady, first, newcand = defaultdict(list), defaultdict(list), defaultdict(list)
    for r in runs:
        seen = set()
        for b in r["ballots"]:
            is_new = b["vote"] not in seen
            seen.add(b["vote"])
            (first if b["index"] == 0 else newcand if is_new else steady)[r["workflow"]].append(b["castGas"])
    g = {w: st.mean(steady[w]) for w in (PUB, PBR, REV)}
    prem_first = {w: st.mean(first[w]) - g[w] for w in (PUB, PBR, REV)}
    prem_new = st.mean(newcand[PUB]) - g[PUB]
    cd = {w: st.mean(b["calldataGas"] for r in runs if r["workflow"] == w for b in r["ballots"]) for w in (PUB, PBR, REV)}
    create = {w: min(r["electionCreateGas"] for r in runs if r["workflow"] == w) for w in (PUB, PBR, REV)}
    verifier = sorted({r["verifierExecutionGas"] for r in runs})
    assert len(verifier) == 1
    model_errors = paper["gas"]
    max_err = max(v["model_mean_diff_error"]["max_abs"] for v in model_errors.values())
    f0 = lambda x: f"{x:,.0f}"
    rows = [
        f"Cast gas per ballot, steady state & {f0(g[PUB])} & {f0(g[PBR])} & {f0(g[REV])} & $g_{{\\mathrm{{pub}}}}$, $g_{{\\mathrm{{com}}}}$\\\\",
        f"\\quad difference to \\Wpub & --- & {f0(g[PBR] - g[PUB])} & {f0(g[REV] - g[PUB])} & $22{{,}}100 + \\varepsilon_{{\\mathrm{{c}}}}$\\\\",
        f"First-ballot premium & {f0(prem_first[PUB])} & {f0(prem_first[PBR])} & {f0(prem_first[REV])} & $2 \\times 17{{,}}100$\\\\",
        f"First vote for a candidate & {f0(prem_new)} & --- & --- & $17{{,}}100$\\\\",
        f"Calldata per cast (bytes; gas) & 356; {f0(cd[PUB])} & 356; {f0(cd[PBR])} & 356; {f0(cd[REV])} & EIP-2028\\\\",
        f"Verifier execution per proof & {f0(verifier[0])} & {f0(verifier[0])} & {f0(verifier[0])} & $217{{,}}900 + \\varepsilon_{{\\mathrm{{v}}}}$\\\\",
        f"Election creation & {f0(create[PUB])} & {f0(create[PBR])} & {f0(create[REV])} & ---\\\\",
    ]
    (ms / "tables" / "tab_gas_rows.tex").write_text("% generated by analysis/make_paper_tables.py\n" + "\n".join(rows) + "\n")

    # ---------------------------------------------------------------- exact numbers cited in the text
    def c(name, outcome, cell):
        r = contrast[(name, outcome, cell)]
        return {k: r[k] for k in ("mean", "ciLow", "ciHigh", "meanRatio", "holmP")}

    rp = paper["result_phase"]["summary"]
    # Table 9 totals cover the cast transactions and the result phase. Election creation
    # (Table 8, without the first-election premium) and the one-time deployments are left
    # out; these numbers show what including creation, or deploying the Poseidon contract
    # once per election, would change.
    with_creation, shift = {}, 0.0
    for name, per in bars.items():
        b = runs_of(dict(elections)[name], PUB)[0]["plannedBallots"]
        tot = {w: per[w]["total_pb"] + create[w] / b for w in (PUB, PBR, REV)}
        pct = {w: (tot[w] / tot[PUB] - 1) * 100 for w in (PBR, REV)}
        old = {w: (per[w]["total_pb"] / per[PUB]["total_pb"] - 1) * 100 for w in (PBR, REV)}
        with_creation[name] = {"B": b, "total_pb": tot, "increase_pct": pct,
                               "change_pct_points": {w: pct[w] - old[w] for w in (PBR, REV)}}
        shift = max(shift, *(abs(pct[w] - old[w]) for w in (PBR, REV)))
    poseidon = paper["fixed_costs"]["setup_gas"]["poseidonHasher"]["min"]
    numbers = {
        "gas_steady": g, "gas_first_premium": prem_first, "gas_new_candidate_premium": prem_new,
        "gas_steady_diff_pbr": g[PBR] - g[PUB], "gas_steady_diff_rev": g[REV] - g[PUB], "gas_rev_minus_pbr": g[REV] - g[PBR],
        "eps_c": g[PBR] - g[PUB] - 22100, "eps_v": verifier[0] - 181000 - 6150 * 6,
        "calldata_gas": cd, "election_create": create, "max_model_error_mean_diff": max_err,
        "time_D13_pbr": c("publisher-public", "proofMs", "DEPTH-D13"),
        "time_D13_rev": c("reveal-public", "proofMs", "DEPTH-D13"),
        "time_D5_pbr": c("publisher-public", "proofMs", "DEPTH-D05"),
        "memory_D13": c("publisher-public", "provingMemoryMiB", "DEPTH-D13"),
        "result": rp,
        "totals_per_ballot": {name: {k: per[k]["total_pb"] for k in per} for name, per in bars.items()},
        "result_time_s": {name: {k: per[k]["time_s"] for k in per} for name, per in bars.items()},
        "median_contrasts": {cell: {k: v for k, v in paper["time"][cell].items() if k.startswith("median:") and "-" in k}
                             for cell in paper["time"]},
        "time_model": paper["time_model"], "time_model_median": paper["time_model_median"],
        "time_model_validation": paper["time_model_validation"],
        "host": {k: v for k, v in paper["host_disturbances"].items() if k != "stalls"},
        "fixed_costs": paper["fixed_costs"],
        "memory_vs_key": paper["memory_vs_key"],
        "memory_controls": {k: v for k, v in paper["memory_controls"].items() if k != "cells"},
        "totals_with_creation": with_creation, "totals_with_creation_max_shift_pct_points": shift,
        "poseidon_deployment_per_ballot": {str(b): poseidon / b for b in (32, 1024)},
    }
    (exp / "analysis" / "paper_numbers.json").write_text(json.dumps(numbers, indent=1, default=str))
    print(json.dumps({k: numbers[k] for k in ("gas_steady", "gas_first_premium", "gas_new_candidate_premium",
                                              "gas_steady_diff_pbr", "gas_steady_diff_rev", "gas_rev_minus_pbr",
                                              "eps_c", "eps_v", "calldata_gas", "election_create",
                                              "max_model_error_mean_diff", "time_D13_pbr", "time_D13_rev",
                                              "time_D5_pbr", "memory_D13")}, indent=1))


if __name__ == "__main__":
    main()
